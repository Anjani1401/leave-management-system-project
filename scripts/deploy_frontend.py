"""Upload the website to the S3 bucket created by `sam deploy`.

Reads the stack outputs, writes frontend/config.js (API URL, Cognito IDs) and
uploads every file in frontend/ with the right Content-Type.

Usage (from the repo root):
  python scripts/deploy_frontend.py --stack leave-mgmt --region ap-south-1
"""
import argparse
import mimetypes
import os
import sys

import boto3
from botocore.exceptions import ClientError

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FRONTEND = os.path.join(ROOT, "frontend")
SKIP = {"config.example.js"}
# Explicit types: on Windows, mimetypes reads the registry and can return the wrong type for .js
TYPES = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
         ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stack", default="leave-mgmt")
    ap.add_argument("--region", default="ap-south-1")
    args = ap.parse_args()

    session = boto3.Session(region_name=args.region)
    try:
        stack = session.client("cloudformation").describe_stacks(StackName=args.stack)["Stacks"][0]
    except ClientError as err:
        sys.exit(f"Could not read stack '{args.stack}': {err}")
    out = {o["OutputKey"]: o["OutputValue"] for o in stack["Outputs"]}

    config = (
        "// Generated by scripts/deploy_frontend.py - do not edit by hand.\n"
        "window.APP_CONFIG = {\n"
        f'  region: "{out["Region"]}",\n'
        f'  apiUrl: "{out["ApiUrl"]}",\n'
        f'  userPoolId: "{out["UserPoolId"]}",\n'
        f'  userPoolClientId: "{out["UserPoolClientId"]}"\n'
        "};\n"
    )
    with open(os.path.join(FRONTEND, "config.js"), "w") as f:
        f.write(config)
    print("Wrote frontend/config.js")

    s3 = session.client("s3")
    bucket = out["FrontendBucketName"]
    for name in sorted(os.listdir(FRONTEND)):
        path = os.path.join(FRONTEND, name)
        if name in SKIP or not os.path.isfile(path):
            continue
        ext = os.path.splitext(name)[1].lower()
        ctype = TYPES.get(ext) or mimetypes.guess_type(name)[0] or "application/octet-stream"
        s3.upload_file(path, bucket, name, ExtraArgs={"ContentType": ctype, "CacheControl": "no-cache"})
        print(f"  uploaded {name} ({ctype})")

    print("\nWebsite:", out["WebsiteUrl"])


if __name__ == "__main__":
    main()
